/**
 * SINGLE SOURCE OF TRUTH for the 16 benchmark sites.
 *
 * Each site carries 28 instrument-derived physical parameters. Feature vectors
 * are computed at module load from those parameters — never hardcoded — so the
 * dataset and the similarity engine can never disagree.
 */

const cites = (...ids: string[]): Citation[] => ids.map(getCitation)

function defineSite(seed: Omit<AnalogSite, 'featureVector'>): AnalogSite {
  return { ...seed, featureVector: computeFeatureVector(seed.rawParameters) }
}

/** Result of converting a raw parameter set into the canonical interface. */
export type { RawParameters }

