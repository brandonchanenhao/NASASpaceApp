export const targetSites: readonly AnalogSite[] = [...moonSites, ...marsSites]

/** Site lookup by stable id. */
export const siteById: ReadonlyMap<string, AnalogSite> = new Map(
  allSites.map((site) => [site.id, site]),
)

/** Look up a site by id, throwing when an unknown id is requested. */
export function getSite(id: string): AnalogSite {
  const site = siteById.get(id)
  if (!site) {
    throw new Error(`Unknown analog site id: ${id}`)
  }
  return site
}
